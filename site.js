  // Drag the sheet down to dismiss: a quick flick counts as much as a long drag.
  const grabber = modal.querySelector(".sheet-grabber");
  let sheetDrag = null;
  grabber.addEventListener("pointerdown", (event) => {
    if (sheetDrag) return;
    sheetDrag = {id:event.pointerId, startY:event.clientY, startTime:event.timeStamp};
    grabber.setPointerCapture(event.pointerId);
    dialog.style.transition = "none";
  });
  grabber.addEventListener("pointermove", (event) => {
    if (event.pointerId !== sheetDrag?.id) return;
    const distance = event.clientY - sheetDrag.startY;
    // Friction upward instead of a hard stop.
    dialog.style.transform = `translateY(${distance > 0 ? distance : -Math.sqrt(-distance)}px)`;
  });
  function endSheetDrag(event) {
    if (event.pointerId !== sheetDrag?.id) return;
    const distance = event.clientY - sheetDrag.startY;
    const velocity = distance / Math.max(event.timeStamp - sheetDrag.startTime, 1);
    const dismiss = event.type === "pointerup" && distance > 24 && (distance > dialog.offsetHeight * .25 || velocity > .11);
    sheetDrag = null;
    dialog.style.transition = "";
    dialog.style.transform = "";
    if (dismiss) closeBooking();
  }
  grabber.addEventListener("pointerup", endSheetDrag);
  grabber.addEventListener("pointercancel", endSheetDrag);

