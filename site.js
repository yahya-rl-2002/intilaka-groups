    if (animate) {
      // A small blur bridges the two states so the swap reads as one change, not two overlapping texts.
      const from = reducedMotion.matches ? {opacity:.5} : {opacity:.4, filter:"blur(2px)"};
      const to = reducedMotion.matches ? {opacity:1} : {opacity:1, filter:"blur(0)"};
      [...result.children].forEach((child) => child.animate([from, to], {duration:220, easing:"ease-out"}));
    }
